#!/bin/sh
# Capture the pinned build/test environment for EKBLOOM into evidence/environment.txt.
#
# Hard rule: project tooling runs ONLY inside the pinned container, never on the host.
# This script sources scripts/lib.sh (which pins the base image digest and the
# derived project tag) and records, each clearly labelled:
#
#   * the derived project image id, the pinned base digest and the Dockerfile sha256;
#   * the in-container Rust toolchain (`rustc -Vv`, `cargo -V`, host triple,
#     `rustc --print target-libdir`);
#   * the kernel (`uname -a`), CPU model + flags and `nproc`;
#   * the `Cargo.lock` sha256 and `git rev-parse HEAD` when available;
#   * the pinned nightly image digest read from scripts/container-fuzz.sh.
#
# Nothing here is fabricated: every value is measured from the pinned environment
# or read from the repository's own source of truth.
#
# Run: sh scripts/capture-environment.sh
set -eu
. "$(dirname "$0")/lib.sh"

OUT="$PROJECT_DIR/evidence/environment.txt"
mkdir -p "$PROJECT_DIR/evidence"

# Pinned base image (source of truth: scripts/lib.sh).
BASE_IMAGE="$(sed -n 's/^RUST_BASE_IMAGE="\([^"]*\)".*/\1/p' "$PROJECT_DIR/scripts/lib.sh")"
# The container image id actually derived from ./Dockerfile.
PROJECT_IMAGE_ID="$(docker image inspect --format '{{.Id}}' "$IMAGE")"
DOCKERFILE_SHA="$(sha256sum "$PROJECT_DIR/Dockerfile" | cut -d' ' -f1)"

# Nightly image pinned by the fuzz/miri/sanitize harnesses (source of truth:
# scripts/container-fuzz.sh).
NIGHTLY_IMAGE="$(sed -n 's/^NIGHTLY_IMAGE="\([^"]*\)".*/\1/p' "$PROJECT_DIR/scripts/container-fuzz.sh")"

# --- in-container toolchain / kernel / CPU (all measured inside the image) ---
RUSTC_VV="$(docker_run rustc -Vv)"
CARGO_V="$(docker_run cargo -V)"
RUSTC_HOST="$(printf '%s\n' "$RUSTC_VV" | sed -n 's/^host: //p')"
TARGET_LIBDIR="$(docker_run rustc --print target-libdir)"
UNAME_LINE="$(docker_run uname -a)"
CPU_MODEL="$(docker_run grep -m1 'model name' /proc/cpuinfo | sed 's/^[^:]*: //')"
CPU_FLAGS="$(docker_run grep -m1 '^flags' /proc/cpuinfo | sed 's/^[^:]*: //')"
NPROC="$(docker_run nproc)"

# --- source provenance (host filesystem; no tooling executed) ---
CARGO_LOCK_SHA="$(sha256sum "$PROJECT_DIR/Cargo.lock" | cut -d' ' -f1)"
if command -v git >/dev/null 2>&1 && [ -d "$PROJECT_DIR/.git" ]; then
    GIT_HEAD="$(git -C "$PROJECT_DIR" rev-parse HEAD 2>/dev/null || echo unavailable)"
else
    GIT_HEAD="unavailable"
fi

{
    echo "# EKBLOOM environment capture"
    echo "# Generated by scripts/capture-environment.sh; do not edit by hand."
    echo "# Toolchain/kernel/CPU lines are measured INSIDE the pinned container."
    echo
    echo "== container image =="
    echo "project_image_tag: $IMAGE"
    echo "project_image_id: $PROJECT_IMAGE_ID"
    echo "base_image: $BASE_IMAGE"
    echo "base_image_digest: ${BASE_IMAGE##*@}"
    echo "dockerfile_sha256: $DOCKERFILE_SHA"
    echo
    echo "== rust toolchain (inside container) =="
    echo "rustc -Vv:"
    printf '%s\n' "$RUSTC_VV" | sed 's/^/  /'
    echo "cargo_version: $CARGO_V"
    echo "target_triple: $RUSTC_HOST"
    echo "rustc_host: $RUSTC_HOST"
    echo "target_libdir: $TARGET_LIBDIR"
    echo
    echo "== kernel & cpu (inside container; shares the host kernel) =="
    echo "uname: $UNAME_LINE"
    echo "cpu_model: $CPU_MODEL"
    echo "cpu_flags: $CPU_FLAGS"
    echo "nproc: $NPROC"
    echo
    echo "== source provenance =="
    echo "cargo_lock_sha256: $CARGO_LOCK_SHA"
    echo "git_head: $GIT_HEAD"
    echo
    echo "== nightly harness image (scripts/container-fuzz.sh) =="
    echo "nightly_image: $NIGHTLY_IMAGE"
    echo "nightly_image_digest: ${NIGHTLY_IMAGE##*@}"
} > "$OUT"

echo "wrote $OUT"
cat "$OUT"
